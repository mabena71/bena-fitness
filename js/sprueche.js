/** Spruch für einen Tag (gleicher Tag = gleicher Spruch). */
export function spruchFuer(date = new Date()) {
  const [y, m, d] = dayKey(date).split('-').map(Number);
  const tage = Math.floor(Date.UTC(y, m - 1, d) / 86400000);
  return SPRUECHE[((tage % SPRUECHE.length) + SPRUECHE.length) % SPRUECHE.length];
}
